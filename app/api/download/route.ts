import { NextRequest } from "next/server";
import { getClaimSession } from "@/lib/supabase";
import type { PipelineResult } from "@/lib/types";

export async function GET(req: NextRequest) {
  const { searchParams } = new URL(req.url);
  const sessionId = searchParams.get("session");
  const docType = searchParams.get("type");

  if (!sessionId || !docType) {
    return new Response("Missing params", { status: 400 });
  }

  const result = (await getClaimSession(sessionId)) as PipelineResult | null;
  if (!result) return new Response("Session not found", { status: 404 });

  const doc = result.documents?.documents?.find((d) => d.type === docType);
  if (!doc) return new Response("Document not found", { status: 404 });

  const content = `${doc.title}
${"=".repeat(doc.title.length)}

Date: ${new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" })}
To: ${doc.recipient}
Send via: ${doc.sendVia}
Deadline: ${doc.deadline}

Legal Citations: ${doc.legalCitations.join(" | ")}

${"─".repeat(60)}

${doc.content}

${"─".repeat(60)}
Generated by MediClaimPilot — AI Medical Bill Auditor & Insurance Denial Fighter
This document is for informational purposes. For complex cases, consult a patient advocate or healthcare attorney.
`;

  return new Response(content, {
    headers: {
      "Content-Type": "text/plain",
      "Content-Disposition": `attachment; filename="${docType}_letter.txt"`,
    },
  });
}
